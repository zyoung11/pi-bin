export class Theme {
	name?: string;
	sourcePath?: string;
	sourceInfo?: SourceInfo;
	private fgColors: Map<ThemeColor, string>;
	private bgColors: Map<ThemeBg, string>;
	private mode: ColorMode;

	constructor(
		fgColors: Record<string, string | number>,
		bgColors: Record<string, string | number>,
		mode: ColorMode,
		options: { name?: string; sourcePath?: string; sourceInfo?: SourceInfo } = {},
	) {
		this.name = options.name;
		this.sourcePath = options.sourcePath;
		this.sourceInfo = options.sourceInfo;
		this.mode = mode;
		this.fgColors = new Map();
		const colors = copyThemeRecord(fgColors);
		const fgView = recordViewOf(fgColors);
		colors.thinkingMax = colorOrDefault(
			fgView["thinkingMax"] as string | number | undefined,
			fgView["thinkingXhigh"] as string | number | undefined,
		);
		colors.searchMatchText = colorOrDefault(
			fgView["searchMatchText"] as string | number | undefined,
			fgView["text"] as string | number | undefined,
		);
		const colorsView = recordViewOf(colors);
		for (const key of THEME_COLOR_KEYS) {
			const value = colorsView[key];
			if (typeof value === "string" || typeof value === "number") {
				this.fgColors.set(key as ThemeColor, fgAnsi(value, mode));
			}
		}
		this.bgColors = new Map();
		const backgrounds = copyThemeRecord(bgColors);
		const bgView = recordViewOf(bgColors);
		backgrounds.scrollbarThumb = colorOrDefault(
			bgView["scrollbarThumb"] as string | number | undefined,
			bgView["selectedBg"] as string | number | undefined,
		);
		backgrounds.searchMatchBg = colorOrDefault(
			bgView["searchMatchBg"] as string | number | undefined,
			bgView["selectedBg"] as string | number | undefined,
		);
		const backgroundsView = recordViewOf(backgrounds);
		for (const key of THEME_BG_KEYS) {
			const value = backgroundsView[key];
			if (typeof value === "string" || typeof value === "number") {
				this.bgColors.set(key as ThemeBg, bgAnsi(value, mode));
			}
		}
	}

	copyStateFrom(other: Theme): void {
		this.name = other.name;
		this.sourcePath = other.sourcePath;
		this.sourceInfo = other.sourceInfo;
		this.fgColors = other.fgColors;
		this.bgColors = other.bgColors;
		this.mode = other.mode;
	}

	fg(color: ThemeColor, text: string): string {
		const ansi = this.fgColors.get(color);
		if (!ansi) throw new Error(`Unknown theme color: ${color}`);
		return `${ansi}${text}\x1b[39m`; // Reset only foreground color
	}

	bg(color: ThemeBg, text: string): string {
		const ansi = this.bgColors.get(color);
		if (!ansi) throw new Error(`Unknown theme background color: ${color}`);
		return `${ansi}${text}\x1b[49m`; // Reset only background color
	}

	bold(text: string): string {
		return chalk.bold(text);
	}

	italic(text: string): string {
		return chalk.italic(text);
	}

	underline(text: string): string {
		return chalk.underline(text);
	}

	inverse(text: string): string {
		return chalk.inverse(text);
	}

	strikethrough(text: string): string {
		return chalk.strikethrough(text);
	}

	getFgAnsi(color: ThemeColor): string {
		const ansi = this.fgColors.get(color);
		if (!ansi) throw new Error(`Unknown theme color: ${color}`);
		return ansi;
	}

	getBgAnsi(color: ThemeBg): string {
		const ansi = this.bgColors.get(color);
		if (!ansi) throw new Error(`Unknown theme background color: ${color}`);
		return ansi;
	}

	getColorMode(): ColorMode {
		return this.mode;
	}

	getThinkingBorderColor(level: ThinkingLevel): (str: string) => string {
		// Map thinking levels to dedicated theme colors
		switch (level) {
			case "off":
				return (str: string) => this.fg("thinkingOff", str);
			case "minimal":
				return (str: string) => this.fg("thinkingMinimal", str);
			case "low":
				return (str: string) => this.fg("thinkingLow", str);
			case "medium":
				return (str: string) => this.fg("thinkingMedium", str);
			case "high":
				return (str: string) => this.fg("thinkingHigh", str);
			case "xhigh":
				return (str: string) => this.fg("thinkingXhigh", str);
			case "max":
				return (str: string) => this.fg("thinkingMax", str);
			default:
				return (str: string) => this.fg("thinkingOff", str);
		}
	}

	getBashModeBorderColor(): (str: string) => string {
		return (str: string) => this.fg("bashMode", str);
	}
}

